import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';
import 'package:get/get.dart';
import 'controllers/auth_controller.dart';
import 'controllers/lookup_controller.dart';
import 'controllers/permission_controller.dart';
import 'controllers/theme_controller.dart';
import 'core/routes/app_pages.dart';
import 'core/routes/app_routes.dart';
import 'core/services/storage_service.dart';
import 'core/theme/app_theme.dart';
import 'widgets/inactivity_watcher.dart';
import 'firebase_options.dart'; // generated by: flutterfire configure

Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();

  try {
    await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);

    // Register core services / controllers once, at app startup.
    final storageService = await StorageService().init();
    Get.put(storageService, permanent: true);
    final auth = Get.put(AuthController(), permanent: true);
    Get.put(PermissionController(), permanent: true);
    Get.put(LookupController(), permanent: true);
    Get.put(ThemeController(), permanent: true);

    // Restore Firebase session (if "Remember me" was ticked). Never block startup > 8 s.
    await auth.restoreSession().timeout(const Duration(seconds: 8), onTimeout: () {});
  } catch (e, st) {
    // Show the real problem on screen instead of a blank page.
    debugPrint('STARTUP ERROR: $e\n$st');
    runApp(_StartupError('$e'));
    return;
  }

  runApp(const RbacApp());
}

class _StartupError extends StatelessWidget {
  final String message;
  const _StartupError(this.message);

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      debugShowCheckedModeBanner: false,
      home: Scaffold(
        body: SafeArea(
          child: SingleChildScrollView(
            padding: const EdgeInsets.all(24),
            child: Column(crossAxisAlignment: CrossAxisAlignment.start, children: [
              const Icon(Icons.error_outline_rounded, color: Colors.red, size: 48),
              const SizedBox(height: 12),
              const Text('App could not start', style: TextStyle(fontSize: 20, fontWeight: FontWeight.w800)),
              const SizedBox(height: 12),
              SelectableText(message, style: const TextStyle(color: Colors.red)),
              const SizedBox(height: 16),
              const Text(
                'Check:\n'
                    '1) flutterfire configure was run for THIS platform (Android).\n'
                    '2) You are running on an Android emulator/phone, not Windows.\n'
                    '3) firebase_core, cloud_firestore, firebase_auth are installed (flutter pub get).',
              ),
            ]),
          ),
        ),
      ),
    );
  }
}

class RbacApp extends StatelessWidget {
  const RbacApp({super.key});

  @override
  Widget build(BuildContext context) {
    final themeController = Get.find<ThemeController>();

    return Obx(() => GetMaterialApp(
      title: 'Bolt Workforce Ledger',
      debugShowCheckedModeBanner: false,
      theme: AppTheme.light,
      darkTheme: AppTheme.dark,
      themeMode: themeController.themeMode,
      initialRoute: AppRoutes.splash,
      getPages: AppPages.pages,
      builder: (context, child) => InactivityWatcher(child: child ?? const SizedBox.shrink()),
      defaultTransition: Transition.fadeIn,
    ));
  }
}